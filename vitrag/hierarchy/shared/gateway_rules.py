"""
gateway_rules.py: what the gateway (nginx) blocks for a given control state.

Two renderings of ONE rule set:
  * decision(state, method, path)  -> used by the Python stand-in gateway and by tests;
  * render_nginx_conf(state)       -> http-level include for the real nginx (map + limit_req_zone),
    regenerated by the controller on every state change followed by a reload (SIGHUP).
A test checks that the generated map and decision() agree on a matrix of states and requests.
"""

from __future__ import annotations

from typing import Any, Optional

from controlstate import BLOCKS, edge_cut, mode_of

# path prefix regex (python/PCRE compatible) -> upstream service
ROUTES: list[tuple[str, str]] = [
    (r"/auth(/|$)", "auth_api"),
    (r"/api(/|$)", "product_api"),
    (r"/orders(/|$)", "order_api"),
    (r"/search(/|$)", "search_api"),
]
WRITE_METHODS = "POST|PUT|PATCH|DELETE"


def rules(state: dict[str, Any]) -> list[tuple[str, str]]:
    """Ordered (regex over "METHOD:/path", reason) rows; first match wins (nginx map regex semantics)."""
    mode = mode_of(state, "nginx")
    out: list[tuple[str, str]] = []
    if mode == "isolated":
        return [(r"^[A-Z]+:/", "mode=isolated; capability=all")]
    for rx, svc in ROUTES:
        if edge_cut(state, "nginx", svc):
            out.append((rf"^[A-Z]+:{rx}", f"edge=nginx-{svc}"))
    if "dependency_calls" in BLOCKS[mode]:
        for rx, _ in ROUTES:
            out.append((rf"^[A-Z]+:{rx}", f"mode={mode}; capability=dependency_calls"))
    if "state_write" in BLOCKS[mode]:
        out.append((rf"^({WRITE_METHODS}):/", f"mode={mode}; capability=state_write"))
    return out


def decision(state: dict[str, Any], method: str, path: str) -> Optional[str]:
    import re
    key = f"{method.upper()}:{path}"
    for rx, reason in rules(state):
        if re.search(rx, key):
            return reason
    return None


def rate_limited(state: dict[str, Any]) -> bool:
    return "bulk_requests" in BLOCKS[mode_of(state, "nginx")] and mode_of(state, "nginx") != "isolated"


def upstream_for(path: str) -> Optional[str]:
    import re
    for rx, svc in ROUTES:
        if re.match(rx, path):
            return svc
    return None


def render_nginx_conf(state: dict[str, Any]) -> str:
    lines = ["# GENERATED by the controller from /control/state.json. Do not edit.",
             'map "$request_method:$uri" $acd_blocked {', '    default "";']
    for rx, reason in rules(state):
        lines.append(f'    "~{rx}" "{reason}";')
    lines += ["}", "",
              "map $remote_addr $acd_rl_key {",
              f'    default {"$binary_remote_addr" if rate_limited(state) else chr(34) + chr(34)};',
              "}",
              "limit_req_zone $acd_rl_key zone=acd_rl:1m rate=8r/s;", ""]
    return "\n".join(lines)
